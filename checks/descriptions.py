    info.setdefault("cwe", meta.get("cwe", []))
    info.setdefault("owasp_api", meta.get("owasp_api", []))
    info.setdefault("owasp_top10", meta.get("owasp_top10", ""))
    info.setdefault("confidence", meta.get("confidence", "medium"))
    return info
